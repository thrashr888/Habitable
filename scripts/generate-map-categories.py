#!/usr/bin/env python3
"""Generate Swift metadata from the provider-docs snapshot in the design research.

Refresh sub.json with the research analyze.py before regenerating for a release.
No provider source or credentials are needed to reproduce the checked-in table.
"""
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
source = root / "docs/design/map-research/sub.json"
values = json.loads(source.read_text())["sub"]
rows = []
for key, value in sorted(values.items()):
    assert not any(c in key + value for c in "\n\r\t"), "Invalid table entry"
    rows.append(key + "\t" + value)
body = "\n".join(rows)
output = "// Generated by scripts/generate-map-categories.py; do not edit.\n"
output += 'enum ResourceMapCategories {\n    static let values: [String: String] = {\n'
output += '        let rows = #"""\n' + body + '\n"""#\n'
output += "        return Dictionary(uniqueKeysWithValues: rows.split(separator: \"\\n\").map { row in\n"
output += "            let pair = row.split(separator: \"\\t\", maxSplits: 1)\n"
output += "            return (String(pair[0]), String(pair[1]))\n        })\n    }()\n}\n"
(root / "Habitable/Models/ResourceMapCategories.swift").write_text(output)
